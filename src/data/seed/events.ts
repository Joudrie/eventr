/**
 * Development seed — Greater Boston / North Shore.
 *
 * These are FABRICATED listings placed at real public locations. No real organization
 * has posted any of this. They exist so the feed can be built and judged against
 * plausible data, per DESIGN.md tell #6: seed data that reads fake makes the whole app
 * read fake. Real town names, real parks and commons, awkward real-world start times,
 * a realistic free/paid mix, and deliberate edge cases.
 *
 * Times are stored as offsets, not fixed dates, so the feed is always populated
 * whenever you open it and so tests stay deterministic. Coordinates are approximate
 * town/landmark centers — close enough for radius work, not survey grade.
 *
 * Replaced by real listings the moment a Supabase project exists.
 */

import type { EventCategory, PriceTier } from '@/types/event';

export type SeedPoster = {
  readonly id: string;
  readonly displayName: string;
  readonly verified: boolean;
};

/** Either a wall-clock slot on a given day, or an offset from right now. */
export type SeedSchedule =
  | {
      readonly kind: 'clock';
      readonly dayOffset: number;
      readonly start: string;
      readonly durationMin: number;
    }
  | { readonly kind: 'relative'; readonly startMin: number; readonly durationMin: number };

export type SeedEvent = {
  readonly id: string;
  readonly posterId: string;
  readonly title: string;
  readonly summary: string;
  readonly description: string | null;
  readonly category: EventCategory;
  readonly priceTier: PriceTier;
  readonly priceLabel: string | null;
  readonly priceFrom: number | null;
  readonly venueName: string;
  readonly addressLine: string | null;
  readonly town: string;
  readonly latitude: number;
  readonly longitude: number;
  readonly schedule: SeedSchedule;
  /** How many fit, when the poster knows. Drives the capacity badge; usually absent. */
  readonly capacity?: number;
  readonly boosted?: boolean;
  readonly ticketUrl?: string;
  readonly contactEmail?: string;
  readonly contactUrl?: string;
  readonly commentsLocked?: boolean;
};

